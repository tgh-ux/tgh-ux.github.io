	// Lazily created Web Audio context shared by all playback operations.
	let _context = null;

	// Promise for the currently loading or decoded atlas, shared by concurrent callers.
	let _bufferPromise = null;

	// Timestamp of the most recent failed atlas load.
	let _lastLoadFailure = 0;

	// Minimum delay between failed atlas-load attempts.
	const ATLAS_RETRY_MS = 60000;


	/* =========================
	   Initialization
	   ========================= */

	/**
	 * Initializes the active language and expands configured clip aliases.
	 *
	 * The language is captured once from Localization. For each alias, a copy of the source clip entry is added when the source exists and
	 * the alias is not already explicitly defined.
	 */
	function _init() {
		_language = Localization.getLanguage();

		if (!CLIPS[_language])
			console.warn(`ClipPlayback: no CLIPS table for language "${_language}"`);

		const clips = CLIPS[_language] ?? {};
		const aliases = CLIP_ALIAS[_language] ?? {};

		Object.entries(aliases).forEach(([alias, source]) => {
			if (clips[source] && !clips[alias])
				clips[alias] = { ...clips[source] };
		});
	}

	_init();


